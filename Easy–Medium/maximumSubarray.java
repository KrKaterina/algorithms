/*
---------------------------------------------- Maximum Subarray -------------------------------------------------

Σου δίνεται ένας πίνακας ακεραίων nums.
Βρες το συνεχόμενο υποσύνολο (contiguous subarray) με το μεγαλύτερο δυνατό άθροισμα και επέστρεψε το άθροισμά του.
Παράδειγμα 1:
nums = [-2, 1, -3, 4, -1, 2, 1, -5, 4]

Απάντηση:6

Επειδή το υποσύνολο [4, -1, 2, 1] έχει άθροισμα 6.

Παράδειγμα 2:
nums = [5, 4, -1, 7, 8]

Απάντηση:23
---------------------------------------------------------------------------------------------------------------------  
*/

public int maxSum(int[] n) {
    int maxSum = n[0];
    int sum = n[0];

    for (int i = 1; i < n.length; i++) {
        sum = Math.max(sum + n[i], n[i]);
        maxSum = Math.max(sum, maxSum);
    }

    return maxSum;
}
